import 'package:drift/drift.dart';
import 'package:drift_flutter/drift_flutter.dart';
import 'package:riverpod_annotation/riverpod_annotation.dart';

import 'app_database.steps.dart';
import 'tables.dart';

export 'tables.dart';

part 'app_database.g.dart';

@DriftDatabase(
  tables: [
    Projects,
    Images,
    ImageEditHistory,
    ImageEditCursor,
    AppMeta,
    ViewPrefs,
    SyncStates,
    BlobSyncs,
    SyncConflicts,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  /// The app's on-device database (in the app support directory).
  AppDatabase.open() : super(driftDatabase(name: 'filbert'));

  @override
  int get schemaVersion => 3;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) => m.createAll(),
    // Generated by `dart run drift_dev make-migrations`; each step sees the
    // schema as it was at that version.
    onUpgrade: stepByStep(
      // View prefs and derived images (m2-design §4).
      from1To2: (m, schema) async {
        await m.createTable(schema.viewPrefs);
        await m.createIndex(schema.viewPrefsProjectId);
        await m.addColumn(schema.images, schema.images.derivedFromJson);
      },
      // Local-only sync tables (m3-design §4).
      from2To3: (m, schema) async {
        await m.createTable(schema.syncState);
        await m.createTable(schema.blobSync);
        await m.createTable(schema.syncConflicts);
      },
    ),
  );
}

@Riverpod(keepAlive: true)
AppDatabase database(Ref ref) {
  final db = AppDatabase.open();
  ref.onDispose(db.close);
  return db;
}
